/**
 * Detects visitor's preferred language based on stored preference, browser language and timezone
 * @param {Object} [options]
 * @param {string} [options.forcedLang]
 * @param {string} [options.navLang]
 * @param {string} [options.timeZone]
 * @returns {'tr' | 'en'}
 */
export function detectVisitorLanguage({ forcedLang, navLang, timeZone } = {}) {
  if (forcedLang === 'tr' || forcedLang === 'en') {
    return forcedLang;
  }

  // Check stored preference
  if (typeof localStorage !== 'undefined') {
    try {
      const stored = localStorage.getItem('social_studio_lang');
      if (stored === 'tr' || stored === 'en') return stored;
    } catch {
      // ignore security restrictions
    }
  }

  // Check navigator language
  const currentNavLang = navLang || (typeof navigator !== 'undefined' ? (navigator.language || navigator.userLanguage || '') : '');
  if (currentNavLang.toLowerCase().startsWith('tr')) {
    return 'tr';
  }

  // Check timezone for Turkey
  const currentTz = timeZone || (typeof Intl !== 'undefined' && Intl.DateTimeFormat ? Intl.DateTimeFormat().resolvedOptions().timeZone : '');
  if (currentTz && (currentTz.includes('Istanbul') || currentTz.includes('Turkey'))) {
    return 'tr';
  }

  // Default to English for international visitors
  return 'en';
}

/**
 * I18n Engine instance for application state
 */
export class I18nEngine {
  constructor(initialLang) {
    this.lang = initialLang || detectVisitorLanguage();
  }

  /**
   * Translates a dot-notated key
   * @param {string} key e.g. 'tabs.studio'
   * @param {Object} [params]
   * @returns {string}
   */
  t(key, params = {}) {
    return translateKey(key, params, this.lang);
  }

  /**
   * Sets current language and persists preference
   * @param {'tr' | 'en'} lang
   */
  setLanguage(lang) {
    if (lang !== 'tr' && lang !== 'en') return;
    this.lang = lang;
    if (typeof localStorage !== 'undefined') {
      try {
        localStorage.setItem('social_studio_lang', lang);
      } catch {
        // ignore
      }
    }
  }

  getLanguage() {
    return this.lang;
  }
}

/**
 * Helper function to look up translation by path
 * @param {string} key
 * @param {Object} params
 * @param {'tr' | 'en'} lang
 * @returns {string}
 */
export function translateKey(key, params = {}, lang = 'tr') {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS.tr;
  const parts = key.split('.');

  let current = dictionary;
  for (const part of parts) {
    if (current && typeof current === 'object' && part in current) {
      current = current[part];
    } else {
      // Fallback to TR if missing in EN
      let fallback = TRANSLATIONS.tr;
      for (const p of parts) {
        if (fallback && typeof fallback === 'object' && p in fallback) {
          fallback = fallback[p];
        } else {
          return key;
        }
      }
      current = fallback;
      break;
    }
  }

  if (typeof current !== 'string') {
    return key;
  }

  // Parameter replacement: {name}
  let result = current;
  for (const [paramKey, paramVal] of Object.entries(params)) {
    result = result.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramVal));
  }
  return result;
}
